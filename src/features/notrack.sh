# shellcheck shell=bash
# ============================================================================
# features/notrack.sh — exempt userspace-proxy data ports from conntrack.
#
# A Reality/Xray/Trojan/Hysteria node terminates every inbound connection in
# userspace and opens its OWN outbound sockets; the conntrack entry created
# for each client connection is pure overhead. Exempting the proxy data
# ports (raw table) keeps the table near-empty and removes the per-packet
# tracking cost on the hottest path on the box.
#
# 2.4.5 fix: the PREROUTING rule now matches only traffic addressed TO this
# host (`-m addrtype --dst-type LOCAL`). pre-2.4.5 matched the port on every packet,
# so a WireGuard/NAT client browsing https://… (dport 443) was untracked,
# skipped MASQUERADE, and lost connectivity on exactly the proxy port.
#
# Never applied to SSH, WireGuard, or any DNAT-forwarded port (NOTRACK skips
# the nat table, so forwarding would break) — all excluded automatically.
# ============================================================================

readonly ST_NOTRACK_UNIT='/etc/systemd/system/server-tools-notrack.service'
# Filled by _notrack_detect_target: "-j CT --notrack" or the legacy alias.
ST_NOTRACK_TARGET=()

# _notrack_detect_target — probe which raw NOTRACK target this kernel takes,
# by adding then removing one harmless rule on an unused high port.
_notrack_detect_target() {
  has_cmd iptables || return 1
  local probe=65533 form
  local -a probe_args=()
  for form in 'CT --notrack' 'NOTRACK'; do
    # Split explicitly: an unquoted $form does NOT word-split under the global
    # IFS, so iptables would receive "-j CT --notrack" as one argument.
    IFS=' ' read -ra probe_args <<<"-j ${form}"
    if iptables -w -t raw -A OUTPUT -p tcp --dport "$probe" "${probe_args[@]}" 2>/dev/null; then
      iptables -w -t raw -D OUTPUT -p tcp --dport "$probe" "${probe_args[@]}" 2>/dev/null ||
        log_warn "Could not remove the NOTRACK probe rule (port ${probe})."
      ST_NOTRACK_TARGET=("${probe_args[@]}")
      return 0
    fi
  done
  return 1
}

# _notrack_specs PORT — rule bodies (chain + matches) for one port.
_notrack_specs() {
  local port="$1" proto
  for proto in tcp udp; do
    printf 'PREROUTING -p %s --dport %s -m addrtype --dst-type LOCAL\n' "$proto" "$port"
    printf 'OUTPUT -p %s --sport %s\n' "$proto" "$port"
  done
}

# _notrack_specs_v2 PORT — the unscoped pre-2.4.5 bodies (migration only).
_notrack_specs_v2() {
  local port="$1" proto
  for proto in tcp udp; do
    printf 'PREROUTING -p %s --dport %s\n' "$proto" "$port"
    printf 'OUTPUT -p %s --sport %s\n' "$proto" "$port"
  done
}

# _notrack_candidates SSH WG DNAT — externally-bound TCP listeners minus the
# ports that must keep conntrack.
_notrack_candidates() {
  has_cmd ss || return 0
  local excl listeners
  excl="$(printf '%s\n%s\n%s\n' "$1" "$2" "$3" | awk '/^[0-9]+$/' | sort -un)"
  listeners="$(ss -tln 2>/dev/null)" || return 0
  ss_listen_ports "$listeners" | ports_subtract "$excl" | paste -sd, -
}

# _notrack_sanitize LIST — valid 1..65535 ports, dedup, comma-joined.
_notrack_sanitize() {
  local tok
  local -a valid=()
  while IFS= read -r tok; do
    if [[ $tok =~ ^[0-9]+$ ]] && ((tok >= 1 && tok <= 65535)); then valid+=("$tok"); fi
  done < <(ports_split "$1")
  ((${#valid[@]})) || return 0
  printf '%s\n' "${valid[@]}" | sort -un | paste -sd, -
}

# _notrack_rules BIN OP SPECS_FN PORT... — run OP (-A/-D) for every spec.
_notrack_rules() {
  local bin="$1" op="$2" specs_fn="$3" port spec
  shift 3
  local -a rule=()
  has_cmd "$bin" || return 0
  for port in "$@"; do
    while IFS= read -r spec; do
      IFS=' ' read -ra rule <<<"$spec"
      if [[ $op == -A ]]; then
        "$bin" -w -t raw -C "${rule[@]}" "${ST_NOTRACK_TARGET[@]}" 2>/dev/null && continue
        "$bin" -w -t raw -A "${rule[@]}" "${ST_NOTRACK_TARGET[@]}" 2>>"$ST_LOG_FILE" ||
          log_warn "Could not add NOTRACK rule (${bin}): ${spec}"
      else
        while "$bin" -w -t raw -C "${rule[@]}" "${ST_NOTRACK_TARGET[@]}" 2>/dev/null; do
          "$bin" -w -t raw -D "${rule[@]}" "${ST_NOTRACK_TARGET[@]}" 2>>"$ST_LOG_FILE" || break
        done
      fi
    done < <("$specs_fn" "$port")
  done
  return 0
}

# _notrack_write_unit PORT... — re-adds the rules at boot (idempotent) and
# removes them on `systemctl disable --now` (so rollback clears them live).
_notrack_write_unit() {
  local port spec bin tgt
  local -a bins=()
  bins+=("$(command -v iptables)")
  has_cmd ip6tables && bins+=("$(command -v ip6tables)")
  tgt="$(join_sp "${ST_NOTRACK_TARGET[@]}")"
  st_track_file "$ST_NOTRACK_UNIT"
  {
    printf '# Generated by %s v%s\n' "$ST_NAME" "$ST_VERSION"
    printf '[Unit]\nDescription=ServerTools conntrack NOTRACK for proxy ports (oneshot, exits after boot)\n'
    printf 'After=network-pre.target %s\nWants=network-pre.target\n\n' "$ST_FW_AFTER"
    printf '[Service]\nType=oneshot\nRemainAfterExit=yes\n'
    for port in "$@"; do
      while IFS= read -r spec; do
        for bin in "${bins[@]}"; do
          printf "ExecStart=-/bin/sh -c '%s -w -t raw -C %s %s 2>/dev/null || %s -w -t raw -A %s %s'\n" \
            "$bin" "$spec" "$tgt" "$bin" "$spec" "$tgt"
          printf 'ExecStop=-%s -w -t raw -D %s %s\n' "$bin" "$spec" "$tgt"
        done
      done < <(_notrack_specs "$port")
    done
    printf '\n[Install]\nWantedBy=multi-user.target\n'
  } >"$ST_NOTRACK_UNIT"
}

# notrack_unit_ports [UNIT] — ports the persisted unit covers (self-describing).
# shellcheck disable=SC2120 # the argument is for tests
notrack_unit_ports() {
  local unit="${1:-$ST_NOTRACK_UNIT}"
  [[ -f $unit ]] || return 0
  awk '{for (i = 1; i < NF; i++) if ($i == "--dport" && $(i + 1) ~ /^[0-9]+$/) print $(i + 1)}' "$unit" | sort -un
}

# notrack_unit_is_v2 — the persisted unit predates the addrtype scope fix.
notrack_unit_is_v2() {
  [[ -f $ST_NOTRACK_UNIT ]] && grep -q -- 'PREROUTING' "$ST_NOTRACK_UNIT" &&
    ! grep -q -- '--dst-type LOCAL' "$ST_NOTRACK_UNIT"
}

# notrack_migrate_v2 — swap pre-2.4.5 unscoped rules for scoped ones, live and in
# the unit. Returns 0 migrated, 2 nothing to do, 1 failed.
notrack_migrate_v2() {
  notrack_unit_is_v2 || return 2
  _notrack_detect_target || return 1
  local -a plist=()
  mapfile -t plist < <(notrack_unit_ports)
  ((${#plist[@]})) || return 2
  local bin
  for bin in iptables ip6tables; do
    _notrack_rules "$bin" -D _notrack_specs_v2 "${plist[@]}"
    _notrack_rules "$bin" -A _notrack_specs "${plist[@]}"
  done
  _notrack_write_unit "${plist[@]}"
  has_cmd systemctl && systemctl daemon-reload 2>>"$ST_LOG_FILE"
  log_info "NOTRACK migrated to host-scoped rules on ports $(join_by , "${plist[@]}")."
  return 0
}

notrack_menu() {
  ui_section "NOTRACK — take proxy ports out of connection tracking"
  printf 'On a userspace-proxy node every inbound connection creates a conntrack\n'
  printf 'entry the proxy never needs. Exempting the proxy data ports keeps the\n'
  printf 'table near-empty and removes the per-packet tracking cost.\n\n'
  printf '%sTrade-off:%s exempted ports lose stateful (ESTABLISHED) firewall matching,\n' "$C_WARN" "$C_RESET"
  printf 'so they must be allowed by an explicit port rule — which a proxy inbound\n'
  printf 'always has. Only traffic addressed to THIS host is exempted, so NAT/VPN\n'
  printf 'clients reaching the same port elsewhere keep working.\n\n'

  if ! has_cmd iptables; then
    log_error "iptables is not available — cannot manage NOTRACK rules."
    return 0
  fi
  if ! _notrack_detect_target; then
    log_error "This kernel's iptables has no usable raw NOTRACK target — skipped."
    return 0
  fi

  local ssh_port wg_ports dnat_ports suggested
  ssh_port="$(detect_ssh_port)"
  wg_ports="$(wg_listen_ports)" || wg_ports=''
  dnat_ports="$(fw_dnat_ports)" || dnat_ports=''
  if grep -qx '\*' <<<"$dnat_ports"; then
    printf '%sA DNAT rule forwards ALL ports of a protocol%s — NOTRACK would break it.\n' "$C_ERR" "$C_RESET"
    printf 'This host is a full NAT relay; NOTRACK does not apply here.\n'
    return 0
  fi
  suggested="$(_notrack_candidates "$ssh_port" "$wg_ports" "$dnat_ports")" || suggested=''

  [[ -n $wg_ports ]] && printf '%sWireGuard%s port(s) %s — excluded (NAT needs conntrack).\n' \
    "$C_KEY" "$C_RESET" "$(paste -sd, - <<<"$wg_ports")"
  [[ -n $dnat_ports ]] && printf '%sDNAT-forwarded%s port(s) %s — excluded (forwarding needs conntrack).\n' \
    "$C_KEY" "$C_RESET" "$(ports_collapse <<<"$dnat_ports")"
  if [[ -z $suggested ]]; then
    printf 'No proxy data ports detected to exempt. Nothing to do.\n'
    return 0
  fi
  printf '%sDetected proxy port(s):%s %s\n\n' "$C_KEY" "$C_RESET" "$suggested"

  local answer ports kept
  read -rp "Ports to exempt [Enter=detected, space/comma separated]: " answer || return 0
  ports="$(_notrack_sanitize "${answer:-$suggested}")" || ports=''
  # Hard rule, even against manual input: never NOTRACK a DNAT'd port.
  if [[ -n $ports && -n $dnat_ports ]]; then
    kept="$(tr ',' '\n' <<<"$ports" | ports_subtract "$dnat_ports" | paste -sd, -)"
    if [[ $kept != "$ports" ]]; then
      printf '%sRemoved DNAT-forwarded port(s)%s from the selection.\n' "$C_WARN" "$C_RESET"
      ports="$kept"
    fi
  fi
  [[ -n $ports ]] || {
    printf 'No valid ports given — nothing to do.\n'
    return 0
  }

  printf '\n%sWill exempt%s tcp+udp on port(s) %s addressed to this host, IPv4%s.\n' \
    "$C_KEY" "$C_RESET" "$ports" "$(has_cmd ip6tables && printf '+IPv6')"
  ui_confirm "Apply NOTRACK now and persist it for reboots?" || return 0

  local -a plist=()
  mapfile -t plist < <(ports_split "$ports")
  local bin
  for bin in iptables ip6tables; do
    _notrack_rules "$bin" -A _notrack_specs "${plist[@]}"
  done
  if systemd_usable; then
    _notrack_write_unit "${plist[@]}"
    systemd_enable_oneshot server-tools-notrack.service || log_warn "NOTRACK will not survive a reboot."
  else
    log_warn "No systemd — NOTRACK is active now but will not survive a reboot."
  fi

  if notrack_verify; then
    printf '%sNOTRACK active%s on %s — those flows no longer touch conntrack.\n' "$C_OK" "$C_RESET" "$ports"
  else
    printf '%sNOTRACK rules did not all verify%s — see the log.\n' "$C_WARN" "$C_RESET"
  fi
  log_info "NOTRACK applied on ports: ${ports}."
  return 0
}

# notrack_verify — 0 every persisted rule live, 3 drift, 2 never configured.
notrack_verify() {
  has_cmd iptables || return 2
  [[ -f $ST_NOTRACK_UNIT ]] || return 2
  local ports port spec
  local -a rule=()
  ports="$(notrack_unit_ports)"
  [[ -n $ports ]] || return 2
  notrack_unit_is_v2 && return 3
  while IFS= read -r port; do
    [[ $port =~ ^[0-9]+$ ]] || continue
    while IFS= read -r spec; do
      IFS=' ' read -ra rule <<<"$spec"
      iptables -w -t raw -C "${rule[@]}" -j CT --notrack 2>/dev/null && continue
      iptables -w -t raw -C "${rule[@]}" -j NOTRACK 2>/dev/null && continue
      return 3
    done < <(_notrack_specs "$port")
  done <<<"$ports"
  return 0
}
