# shellcheck shell=bash
# ============================================================================
# features/ipv6.sh — optional, reversible full IPv6 disable.
#
# Some VPN stacks leak or lag over IPv6: happy-eyeballs races, half-configured
# SLAAC, or AAAA answers with no working v6 route. This switches the IPv6 stack
# off completely — no reboot, no GRUB edit — undone by one Enable (or a normal
# rollback). It is deliberately NOT part of Quick Optimize: on a v6-only host
# it can cut network access, so it stays opt-in (menu i, or `st --ipv6 off`).
#
# Two layers, because a sysctl file alone does not survive a reboot: it sets
# `all`/`default` early in boot, then systemd-networkd / NetworkManager bring
# the links up and switch IPv6 back ON per interface. A oneshot unit that
# runs after the network is up turns it off again on every link, and exits.
# ============================================================================

# Sorts after Debian's 99-sysctl.conf, like the main tuning file.
readonly ST_IPV6_SYSCTL='/etc/sysctl.d/99-zz-server-tools-ipv6.conf'
readonly ST_IPV6_SYSCTL_LEGACY='/etc/sysctl.d/99-server-tools-ipv6.conf'
readonly ST_IPV6_UNIT='/etc/systemd/system/server-tools-ipv6.service'

# _ipv6_present — 0 when the kernel exposes the IPv6 stack at all (a kernel
# built or booted without IPv6 has no disable_ipv6 knob, so sysctl_get -> "?").
_ipv6_present() {
  [[ "$(sysctl_get net.ipv6.conf.all.disable_ipv6)" != '?' ]]
}

# _ipv6_disabled_live — 0 when IPv6 is off globally AND on every interface
# (a link re-enabled by networkd after boot counts as enabled).
_ipv6_disabled_live() {
  [[ "$(sysctl_get net.ipv6.conf.all.disable_ipv6)" == 1 ]] || return 1
  [[ -z "$(_ipv6_enabled_links)" ]]
}

# _ipv6_enabled_links — interfaces that still have IPv6 switched on.
_ipv6_enabled_links() {
  local f name
  for f in /proc/sys/net/ipv6/conf/*/disable_ipv6; do
    [[ -r $f ]] || continue
    name="${f%/disable_ipv6}"
    name="${name##*/}"
    [[ $name == all || $name == default ]] && continue
    [[ "$(cat "$f" 2>/dev/null)" == 0 ]] && printf '%s\n' "$name"
  done
  return 0
}

# _ipv6_managed — 0 when ServerTools is the one that disabled IPv6 here.
_ipv6_managed() { [[ -f $ST_IPV6_SYSCTL || -f $ST_IPV6_SYSCTL_LEGACY ]]; }

# ipv6_state — one word for menus and the CLI.
ipv6_state() {
  if ! _ipv6_present; then
    printf 'absent'
  elif _ipv6_disabled_live; then
    printf 'off'
  elif _ipv6_managed; then
    printf 'drift'
  else
    printf 'on'
  fi
}

# _ipv6_global_addrs — global-scope IPv6 addresses currently configured.
_ipv6_global_addrs() {
  has_cmd ip || return 0
  ip -6 addr show scope global 2>/dev/null | awk '/inet6 / {print $2}' || true
}

# _ipv6_ssh_is_v6 — 0 when THIS SSH session arrived over IPv6 (disabling would
# drop it). SSH_CONNECTION = "clientIP clientPort serverIP serverPort".
_ipv6_ssh_is_v6() {
  local srv
  [[ -n ${SSH_CONNECTION:-} ]] || return 1
  # SSH_CONNECTION is space-separated, but the tool's global IFS is $'\n\t'
  # (no space) — without an explicit space here every field lands empty.
  IFS=' ' read -r _ _ srv _ <<<"$SSH_CONNECTION"
  [[ $srv == *:* ]]
}

# _ipv6_v6_only — 0 when the host has no IPv4 default route but does have an
# IPv6 one: disabling IPv6 there would strand it off the network.
_ipv6_v6_only() {
  has_cmd ip || return 1
  local v4 v6
  v4="$(ip -4 route show default 2>/dev/null)" || v4=''
  v6="$(ip -6 route show default 2>/dev/null)" || v6=''
  [[ -z $v4 && -n $v6 ]]
}

# _ipv6_off_now — switch IPv6 off globally and on every existing link.
_ipv6_off_now() {
  local f
  if has_cmd sysctl; then
    sysctl -p "$ST_IPV6_SYSCTL" >/dev/null 2>>"$ST_LOG_FILE" ||
      log_warn "sysctl reported errors applying the IPv6 disable (see log)."
  fi
  for f in /proc/sys/net/ipv6/conf/*/disable_ipv6; do
    [[ -w $f ]] && printf '1\n' >"$f" 2>>"$ST_LOG_FILE"
  done
  return 0
}

# _ipv6_write_unit — the boot-time re-assertion (see the header).
_ipv6_write_unit() {
  systemd_usable || {
    log_warn "No systemd — IPv6 is off now, but interfaces may turn it back on after a reboot."
    return 3
  }
  st_write_file "$ST_IPV6_UNIT" "# Generated by ${ST_NAME}
[Unit]
Description=ServerTools: IPv6 off on every interface (oneshot, exits after boot)
After=network-online.target systemd-networkd.service NetworkManager.service
Wants=network-online.target

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/bin/sh -c 'for f in /proc/sys/net/ipv6/conf/*/disable_ipv6; do echo 1 > \"\$\$f\"; done'

[Install]
WantedBy=multi-user.target" || log_debug "ipv6 unit unchanged"
  systemd_enable_oneshot server-tools-ipv6.service
}

# ipv6_disable [yes] — "yes" = non-interactive (CLI): no prompts, and the
# risky cases (IPv6-only host, SSH over IPv6) are refused instead of asked.
ipv6_disable() {
  local assume="${1:-}"
  if ! _ipv6_present; then
    printf 'IPv6 is not present on this kernel (already fully disabled). Nothing to do.\n'
    return 0
  fi
  # Safety: never strand a host that reaches the network only over IPv6.
  if _ipv6_v6_only; then
    printf '%sRefusing:%s this host has no IPv4 default route but does have an IPv6\n' "$C_ERR" "$C_RESET"
    printf 'one — disabling IPv6 would cut it off the network. Nothing changed.\n'
    return 2
  fi

  if [[ $assume != yes ]]; then
    printf 'This switches the IPv6 stack OFF completely on every interface; the\n'
    printf 'server keeps working over IPv4 only. It stays off after reboots and is\n'
    printf 'reversible at any time.\n\n'
    printf '%sBefore you do this:%s\n' "$C_WARN" "$C_RESET"
    printf '  • A service listening on %s[::]%s (dual-stack) may need switching to\n' "$C_KEY" "$C_RESET"
    printf '    0.0.0.0, or it can fail to start after a reboot.\n'
    printf '  • Do not do this if your VPN actually serves IPv6 to clients.\n\n'
  fi

  if _ipv6_ssh_is_v6; then
    printf '%sWarning:%s your current SSH session is over IPv6 — it will drop the\n' "$C_ERR" "$C_RESET"
    printf 'moment IPv6 goes down. Reconnect over IPv4 first, or keep a console open.\n'
    if [[ $assume == yes ]]; then
      printf 'Refused in non-interactive mode. Nothing changed.\n'
      return 2
    fi
    ui_confirm "Continue disabling IPv6 anyway?" || return 2
  fi

  if [[ $assume != yes ]]; then
    ui_confirm "Disable IPv6 completely now?" || return 2
  fi

  st_write_file "$ST_IPV6_SYSCTL" "# Generated by ${ST_NAME} — full IPv6 disable.
# Reversible: st --ipv6 on (or menu i). server-tools-ipv6.service re-applies
# it per interface after boot, when the network manager has turned it back on.
net.ipv6.conf.all.disable_ipv6 = 1
net.ipv6.conf.default.disable_ipv6 = 1
net.ipv6.conf.lo.disable_ipv6 = 1" || log_debug "ipv6 drop-in unchanged"
  if [[ -f $ST_IPV6_SYSCTL_LEGACY ]]; then
    st_track_file "$ST_IPV6_SYSCTL_LEGACY"
    rm -f "$ST_IPV6_SYSCTL_LEGACY"
  fi
  _ipv6_off_now
  local rc=0
  _ipv6_write_unit || rc=3

  if _ipv6_disabled_live; then
    local left
    left="$(_ipv6_global_addrs | paste -sd' ' -)" || left=''
    printf '\n%sIPv6 disabled%s on every interface; it stays off after reboots.\n' "$C_OK" "$C_RESET"
    [[ -n $left ]] &&
      printf '%sNote:%s a few addresses linger until services restart or a reboot: %s\n' \
        "$C_MUTED" "$C_RESET" "$left"
  else
    printf '\n%sIPv6 is still on for:%s %s — see the log.\n' "$C_WARN" "$C_RESET" \
      "$(_ipv6_enabled_links | paste -sd' ' -)"
    rc=3
  fi
  log_info "IPv6 disabled via ${ST_IPV6_SYSCTL} + server-tools-ipv6.service."
  return "$rc"
}

ipv6_enable() {
  local f
  if has_cmd systemctl && [[ -f $ST_IPV6_UNIT ]]; then
    systemctl disable server-tools-ipv6.service >/dev/null 2>>"$ST_LOG_FILE" ||
      log_warn "Could not disable server-tools-ipv6.service."
  fi
  for f in "$ST_IPV6_UNIT" "$ST_IPV6_SYSCTL" "$ST_IPV6_SYSCTL_LEGACY"; do
    [[ -f $f ]] || continue
    st_track_file "$f"
    rm -f "$f" || log_warn "Could not remove ${f}."
  done
  # The files are gone, but the running values must be reset too, then a
  # full reload lets any other drop-in reassert its own intent.
  if has_cmd sysctl; then
    local k
    for k in all default lo; do
      sysctl -w "net.ipv6.conf.${k}.disable_ipv6=0" >/dev/null 2>>"$ST_LOG_FILE" ||
        log_warn "Could not re-enable IPv6 on '${k}' live."
    done
    sysctl --system >/dev/null 2>>"$ST_LOG_FILE" ||
      log_warn "sysctl --system reported errors during IPv6 re-enable (see log)."
  fi

  if [[ "$(sysctl_get net.ipv6.conf.all.disable_ipv6)" == 1 ]]; then
    printf '%sIPv6 still shows disabled%s — a reboot will fully restore it.\n' "$C_WARN" "$C_RESET"
  else
    printf '%sIPv6 re-enabled.%s Interfaces reacquire addresses via RA/DHCPv6.\n' "$C_OK" "$C_RESET"
  fi
  log_info "IPv6 re-enabled (drop-in and unit removed)."
  return 0
}

# ipv6_verify — doctor contract: 0 in effect, 2 not configured, 3 drift
# (including a single interface that came back with IPv6 on).
ipv6_verify() {
  _ipv6_managed || return 2
  _ipv6_present || return 0
  _ipv6_disabled_live && return 0
  return 3
}

# ipv6_cli ACTION — `st --ipv6 on|off|status`.
ipv6_cli() {
  case "$1" in
    off)
      local rc=0
      ipv6_disable yes || rc=$?
      # A refusal (2 inside the feature) is a failed request on the CLI.
      ((rc == 2)) && return 1
      return "$rc"
      ;;
    on)
      if _ipv6_managed; then
        ipv6_enable
      else
        printf 'IPv6 was not disabled by ServerTools — nothing to undo.\n'
      fi
      ;;
    status)
      printf 'IPv6: %s\n' "$(ipv6_state)"
      local links
      links="$(_ipv6_enabled_links | paste -sd' ' -)"
      [[ $(ipv6_state) == drift ]] && printf 'Still on for: %s (re-run: st --ipv6 off)\n' "$links"
      [[ $(ipv6_state) == drift ]] && return 3
      return 0
      ;;
  esac
}

# ipv6_control — the interactive screen: show state, then disable or enable.
ipv6_control() {
  ui_section "IPv6 on / off"
  printf 'IPv6 can cause connection races, leaks or lag on some VPN setups. Here\n'
  printf 'you switch the whole IPv6 stack off (IPv4 keeps working) or back on —\n'
  printf 'reversible, no reboot, and it stays that way after reboots.\n'

  local state label addrs
  state="$(ipv6_state)"
  case "$state" in
    absent) label='not present (kernel-level off)' ;;
    off) label="$(_ipv6_managed && printf 'disabled (by ServerTools)' || printf 'disabled (outside ServerTools)')" ;;
    drift) label="partly back on: $(_ipv6_enabled_links | paste -sd' ' -)" ;;
    *) label='enabled' ;;
  esac
  addrs="$(_ipv6_global_addrs | paste -sd' ' -)" || addrs=''

  printf '\n'
  ui_kv "IPv6 stack" "$label"
  ui_kv "Global addresses" "${addrs:-none}"
  printf '\n'

  case "$state" in
    absent) printf 'Nothing to manage — this kernel has no IPv6 stack.\n' ;;
    drift)
      if ui_confirm_yes "Turn IPv6 off again on those interfaces (and keep it off after reboots)?"; then
        ipv6_disable yes || log_debug "ipv6 re-disable reported a problem (shown above)"
      elif ui_confirm "Re-enable IPv6 instead?"; then
        ipv6_enable
      fi
      ;;
    off)
      if _ipv6_managed; then
        if ui_confirm "Re-enable IPv6 now?"; then ipv6_enable; fi
      else
        printf 'IPv6 is already disabled here (not by ServerTools) — left unchanged.\n'
      fi
      ;;
    *) ipv6_disable || log_debug "ipv6 disable not completed (shown above)" ;;
  esac
  return 0
}
