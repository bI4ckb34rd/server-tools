# shellcheck shell=bash
# ============================================================================
# features/flowtable.sh — OPT-IN nftables software fast path for forwarders.
#
# After the first packets of a forwarded connection pass the full netfilter
# path (NAT decided, conntrack established), a flowtable lets the kernel
# forward the remaining packets straight from the ingress hook — skipping
# routing, the netfilter chains and most of conntrack. On a NAT relay or VPN
# gateway that is usually the single biggest CPU saving available.
#
# Opt-in only, because it changes semantics: offloaded packets bypass later
# netfilter hooks, so per-rule iptables counters, traffic accounting built on
# them, and filtering of ESTABLISHED flows no longer see those packets.
#
# Persistence: a oneshot unit runs a generated script that waits briefly for
# the tunnel devices (they are often created by other units), loads the
# table, and exits. ExecStop deletes the table, so rollback clears it live.
# ============================================================================

readonly ST_FT_TABLE='server_tools_ft'
readonly ST_FT_SCRIPT='/etc/server-tools/flowtable.sh'
readonly ST_FT_UNIT='/etc/systemd/system/server-tools-flowtable.service'

# _ft_devices — the uplink plus every kernel tunnel / VPN device that is up.
_ft_devices() {
  local t name kind _rest
  [[ -n $ST_F_IFACE ]] && printf '%s\n' "$ST_F_IFACE"
  for t in "${ST_F_TUNNELS[@]-}"; do
    [[ -n $t ]] || continue
    IFS='|' read -r name kind _rest <<<"$t"
    [[ -d /sys/class/net/$name ]] && printf '%s\n' "$name"
  done
  return 0
}

# _ft_ruleset DEV... — the nft ruleset text.
_ft_ruleset() {
  local devs
  devs="$(join_by ', ' "$@")"
  cat <<EOF
table inet ${ST_FT_TABLE} {
  flowtable ft {
    hook ingress priority 0
    devices = { ${devs} }
  }
  chain forward {
    type filter hook forward priority filter; policy accept;
    meta l4proto { tcp, udp } ct state established flow add @ft
  }
}
EOF
}

# The generated script's own variables must stay unexpanded here.
# shellcheck disable=SC2016
_ft_write_script() {
  local -a devs=("$@")
  local nft
  nft="$(command -v nft)"
  st_track_file "$ST_FT_SCRIPT"
  mkdir -p "$(dirname "$ST_FT_SCRIPT")"
  {
    printf '#!/bin/sh\n'
    printf '# Generated by %s v%s — nftables flowtable fast path (oneshot).\n' "$ST_NAME" "$ST_VERSION"
    printf '# Waits up to 30 s for the devices, then loads only those present.\n'
    printf 'devs=""\nfor i in $(seq 1 30); do\n  missing=0\n'
    printf '  for d in %s; do [ -d "/sys/class/net/$d" ] || missing=1; done\n' "$(join_sp "${devs[@]}")"
    printf '  [ "$missing" = 0 ] && break\n  sleep 1\ndone\n'
    printf 'for d in %s; do [ -d "/sys/class/net/$d" ] && devs="${devs:+$devs, }$d"; done\n' "$(join_sp "${devs[@]}")"
    printf '[ -n "$devs" ] || exit 0\n'
    printf '%s delete table inet %s 2>/dev/null\n' "$nft" "$ST_FT_TABLE"
    printf '%s -f - <<EOF\n' "$nft"
    printf 'table inet %s {\n  flowtable ft {\n    hook ingress priority 0\n    devices = { $devs }\n  }\n' "$ST_FT_TABLE"
    printf '  chain forward {\n    type filter hook forward priority filter; policy accept;\n'
    printf '    meta l4proto { tcp, udp } ct state established flow add @ft\n  }\n}\nEOF\n'
  } >"$ST_FT_SCRIPT"
  chmod 0755 "$ST_FT_SCRIPT"

  st_track_file "$ST_FT_UNIT"
  {
    printf '# Generated by %s v%s\n' "$ST_NAME" "$ST_VERSION"
    printf '[Unit]\nDescription=ServerTools nftables flowtable fast path (oneshot, exits after boot)\n'
    printf 'After=network-online.target %s\nWants=network-online.target\n\n' "$ST_FW_AFTER"
    printf '[Service]\nType=oneshot\nRemainAfterExit=yes\n'
    printf 'ExecStart=%s\n' "$ST_FT_SCRIPT"
    printf 'ExecStop=-%s delete table inet %s\n' "$nft" "$ST_FT_TABLE"
    printf '\n[Install]\nWantedBy=multi-user.target\n'
  } >"$ST_FT_UNIT"
}

flowtable_menu() {
  ui_section "Forwarding fast path (nftables flowtable)"
  facts_collect
  printf 'Established forwarded connections skip routing and the netfilter chains.\n'
  printf 'Typically the largest CPU saving on a NAT relay / VPN gateway.\n\n'
  printf '%sTrade-off:%s offloaded packets bypass later netfilter hooks — iptables\n' "$C_WARN" "$C_RESET"
  printf 'counters, traffic accounting built on them and filtering of established\n'
  printf 'flows stop seeing them. New connections are still fully filtered.\n\n'

  if ! fw_has_nft; then
    log_error "nft is not installed — the flowtable needs nftables (apt install nftables)."
    return 0
  fi
  if fw_nft_table_present inet "$ST_FT_TABLE"; then
    printf 'The fast path is %sactive%s.\n' "$C_OK" "$C_RESET"
    if ui_confirm "Remove it now?"; then
      nft delete table inet "$ST_FT_TABLE" 2>>"$ST_LOG_FILE" || log_warn "Could not delete the flowtable."
      if systemd_usable; then
        systemctl disable server-tools-flowtable.service >/dev/null 2>>"$ST_LOG_FILE" ||
          log_warn "Could not disable server-tools-flowtable.service."
      fi
      printf 'Fast path removed.\n'
    fi
    return 0
  fi

  local -a devs=()
  mapfile -t devs < <(_ft_devices | sort -u)
  if ((${#devs[@]} == 0)); then
    log_error "No uplink or tunnel device found to offload."
    return 0
  fi
  ui_kv "Devices" "$(join_by ', ' "${devs[@]}")"
  if ! _ft_ruleset "${devs[@]}" | nft -c -f - 2>>"$ST_LOG_FILE"; then
    log_error "This kernel rejected the flowtable (needs nf_flow_table, kernel ≥ 4.17) — nothing changed."
    return 0
  fi
  ui_confirm "Enable the fast path now and persist it?" || return 0

  if ! _ft_ruleset "${devs[@]}" | nft -f - 2>>"$ST_LOG_FILE"; then
    log_error "Loading the flowtable failed — see the log."
    return 0
  fi
  if systemd_usable; then
    _ft_write_script "${devs[@]}"
    systemd_enable_oneshot server-tools-flowtable.service || log_warn "The fast path will not survive a reboot."
  fi
  printf '%sFast path active%s on %s. Compare CPU with: st --diagnose\n' "$C_OK" "$C_RESET" "$(join_by ', ' "${devs[@]}")"
  log_info "Flowtable fast path enabled on $(join_by ', ' "${devs[@]}")."
  return 0
}

# flowtable_verify — doctor contract.
flowtable_verify() {
  [[ -f $ST_FT_UNIT ]] || return 2
  systemd_usable && ! systemctl is-enabled --quiet server-tools-flowtable.service 2>/dev/null && return 2
  fw_nft_table_present inet "$ST_FT_TABLE" && return 0
  return 3
}
