# shellcheck shell=bash
# ============================================================================
# tuners/sysctl.sh — kernel tuning. Implements docs/SYSCTL.md: a base layer
# for every host plus sections switched on by the POLICY decisions (never by
# role names directly). Every written file is tracked for rollback, and every
# apply ends in sysctl_verify() comparing the live kernel to the intent.
# ============================================================================

# The name sorts AFTER Debian/Ubuntu's 99-sysctl.conf (a symlink to
# /etc/sysctl.conf) and other 99-* files: systemd-sysctl applies files in
# name order, so the old 99-server-tools.conf lost every key a panel or
# installer had put into /etc/sysctl.conf — "tuning gone after reboot".
readonly ST_SYSCTL_FILE='/etc/sysctl.d/99-zz-server-tools.conf'
readonly ST_SYSCTL_FILE_LEGACY='/etc/sysctl.d/99-server-tools.conf'
readonly ST_SYSCTL_MAIN='/etc/sysctl.conf'
readonly ST_MODULES_FILE='/etc/modules-load.d/server-tools.conf'
readonly ST_MODPROBE_FILE='/etc/modprobe.d/server-tools.conf'

# _sysctl_reserved_ports — service ports inside our ephemeral range, so an
# outgoing connection can never grab a panel/node listener. Consecutive
# ports collapse into ranges; capped at 64 entries. Extra ports come from the
# `reserved_ports` config key (UDP-only services, inbounds added later).
_sysctl_reserved_ports() {
  local detected extra
  detected="$(listening_service_ports)" || detected=''
  extra="$(config_get reserved_ports)"
  [[ -n $extra ]] && detected+=$'\n'"$(ports_expand "$extra")"
  [[ -n ${detected//[[:space:]]/} ]] || return 0
  ports_collapse <<<"$detected" | tr ',' '\n' | awk 'NR <= 64' | paste -sd, -
}

# _sysctl_triple_ceiling KEY MIN DEFAULT MAX — for tcp_rmem/tcp_wmem: each
# field is the greater of ours and the running kernel's. The middle field is
# the initial buffer of every new socket and modern kernels raised it
# (131072 on 6.x); a hardcoded triple silently shrank it (v2.4.1).
_sysctl_triple_ceiling() {
  local key="$1" cur i
  local -a want=("$2" "$3" "$4") live=()
  cur="$(sysctl_get "$key")"
  if [[ $cur =~ ^[0-9]+[[:space:]]+[0-9]+[[:space:]]+[0-9]+$ ]]; then
    IFS=$' \t' read -ra live <<<"$cur"
    for i in 0 1 2; do
      if ((live[i] > want[i])); then want[i]="${live[i]}"; fi
    done
  fi
  printf '%s = %s %s %s\n' "$key" "${want[0]}" "${want[1]}" "${want[2]}"
}

# _sysctl_ceiling KEY TARGET — "KEY = max(running, TARGET)". Modern kernels
# ship high defaults for capacity keys; lowering them would be a regression.
_sysctl_ceiling() {
  local key="$1" target="$2" cur
  cur="$(sysctl_get "$key")"
  [[ $cur =~ ^[0-9]+$ ]] && ((cur > target)) && target="$cur"
  printf '%s = %s\n' "$key" "$target"
}

_sysctl_render() {
  local buf_bytes=$((ST_BUF_MB * 1048576))
  local ram_mb ram_pages swappiness=10 fastopen=3
  ram_mb="$(mem_total_mb)"
  ram_pages=$((ram_mb * 256)) # 4 KiB pages

  # Compressed swap is far faster than disk swap, so let the kernel use it.
  [[ "$(swap_backend_active)" == zram ]] && swappiness=100
  # TFO server-side adds a fingerprinting surface on DPI-exposed hosts and
  # some middleboxes drop SYNs with data: forwarding hosts keep client-only.
  ((ST_P_FORWARD)) && fastopen=1

  cat <<EOF
# Generated by ${ST_NAME} v${ST_VERSION} (roles=${ST_ROLES// /,}, tier=${ST_TIER})
# The rationale for every key lives in docs/SYSCTL.md:
# ${ST_REPO_URL}

# --- Congestion control & queueing
net.core.default_qdisc = ${ST_QDISC}
net.ipv4.tcp_congestion_control = ${ST_CC}

# --- Connection accept path (tier ${ST_TIER})
net.core.somaxconn = ${ST_SOMAXCONN}
net.ipv4.tcp_max_syn_backlog = ${ST_SOMAXCONN}
net.core.netdev_max_backlog = ${ST_NETDEV_BACKLOG}
net.ipv4.tcp_syncookies = 1

# --- Ports, timers, keepalive
net.ipv4.ip_local_port_range = 10240 65535
net.ipv4.tcp_fin_timeout = 30
net.ipv4.tcp_tw_reuse = 1
net.ipv4.tcp_keepalive_time = 300
net.ipv4.tcp_keepalive_intvl = 60
net.ipv4.tcp_keepalive_probes = 5
net.ipv4.tcp_slow_start_after_idle = 0
net.ipv4.tcp_no_metrics_save = 1
net.ipv4.tcp_fastopen = ${fastopen}
net.ipv4.tcp_notsent_lowat = 16384
net.ipv4.tcp_rfc1337 = 1
net.ipv4.tcp_mtu_probing = 1
net.ipv4.tcp_min_snd_mss = 512

# --- Buffers (tier ${ST_TIER})
net.core.rmem_max = ${buf_bytes}
net.core.wmem_max = ${buf_bytes}
net.core.rmem_default = 262144
net.core.wmem_default = 262144
$(_sysctl_triple_ceiling net.ipv4.tcp_rmem 4096 87380 "${buf_bytes}")
$(_sysctl_triple_ceiling net.ipv4.tcp_wmem 4096 65536 "${buf_bytes}")
net.ipv4.udp_rmem_min = 16384
net.ipv4.udp_wmem_min = 16384
$(_sysctl_ceiling net.core.optmem_max 131072)

# --- System capacity (ceilings — never below the running kernel's own value)
$(_sysctl_ceiling fs.file-max 2097152)
$(_sysctl_ceiling fs.nr_open 2097152)
$(_sysctl_ceiling vm.max_map_count 262144)
$(_sysctl_ceiling fs.inotify.max_user_instances 8192)
$(_sysctl_ceiling fs.inotify.max_user_watches 524288)
vm.swappiness = ${swappiness}
net.ipv4.icmp_echo_ignore_broadcasts = 1
net.ipv4.icmp_ignore_bogus_error_responses = 1
EOF

  if ((ST_P_FORWARD)); then
    # More packets per softirq poll before yielding. The time budget
    # (netdev_budget_usecs) is deliberately left alone: its default is
    # 2 jiffies, i.e. already 8 ms on the HZ=250 kernels Debian/Ubuntu ship.
    cat <<EOF

# --- Packet path (high packet-rate roles)
$(_sysctl_ceiling net.core.netdev_budget 600)
EOF
  fi

  if ((ST_P_RFS)); then
    cat <<EOF

# --- RFS global flow table (paired with per-queue rps_flow_cnt, tuners/nic.sh)
net.core.rps_sock_flow_entries = 32768
EOF
  elif [[ "$(sysctl_get net.core.rps_sock_flow_entries)" =~ ^[1-9] ]]; then
    # RFS is not useful for these roles but a previous run enabled it:
    # return the table to the kernel default instead of leaving it live.
    cat <<EOF

# --- RFS not useful for these roles (no local sockets to follow)
net.core.rps_sock_flow_entries = 0
EOF
  fi

  if ((ST_EXPECTED_USERS > 0)); then
    cat <<EOF

# --- TCP memory bounds (user-based capacity mode: ${ST_EXPECTED_USERS} users)
net.ipv4.tcp_mem = $((ram_pages * 10 / 100)) $((ram_pages * 13 / 100)) $((ram_pages * 16 / 100))
EOF
  fi

  if [[ $ST_TIER == L || $ST_TIER == XL ]]; then
    local tw_buckets=524288 max_orphans=131072
    if [[ $ST_TIER == XL ]]; then
      tw_buckets=1048576
      max_orphans=262144
    fi
    cat <<EOF

# --- High-churn caps (tier ${ST_TIER})
net.ipv4.tcp_max_tw_buckets = ${tw_buckets}
net.ipv4.tcp_max_orphans = ${max_orphans}
EOF
  fi

  if [[ -n $ST_P_OVERCOMMIT ]] || ((ST_P_DIRTY)); then
    printf '\n# --- Memory behaviour (database host)\n'
    [[ -n $ST_P_OVERCOMMIT ]] && printf 'vm.overcommit_memory = %s\n' "$ST_P_OVERCOMMIT"
    ((ST_P_DIRTY)) && printf 'vm.dirty_background_ratio = 5\nvm.dirty_ratio = 10\n'
  fi

  local reserved
  reserved="$(_sysctl_reserved_ports)" || reserved=''
  if [[ -n $reserved ]]; then
    cat <<EOF

# --- Listening ports inside the ephemeral range, reserved automatically
net.ipv4.ip_local_reserved_ports = ${reserved}
EOF
  fi

  if ((ST_P_CONNTRACK)); then
    # Ceiling for the table size: entries cost RAM only when used, so a
    # larger running value is never lowered.
    cat <<EOF

# --- Connection tracking (sized for tier ${ST_TIER}; idle flows expire —
# --- the kernel default for established TCP is 5 DAYS)
$(_sysctl_ceiling net.netfilter.nf_conntrack_max "$ST_CONNTRACK")
net.netfilter.nf_conntrack_tcp_timeout_established = ${ST_P_CT_EST}
net.netfilter.nf_conntrack_tcp_timeout_time_wait = 60
net.netfilter.nf_conntrack_tcp_timeout_close_wait = 30
net.netfilter.nf_conntrack_udp_timeout = 30
net.netfilter.nf_conntrack_udp_timeout_stream = ${ST_P_UDP_STREAM}
net.netfilter.nf_conntrack_generic_timeout = 300
EOF
  fi

  if ((ST_P_FORWARD)); then
    cat <<EOF

# --- Forwarding: routing + router hardening
net.ipv4.ip_forward = 1
net.ipv4.conf.all.rp_filter = 2
net.ipv4.conf.default.rp_filter = 2
net.ipv4.conf.all.accept_redirects = 0
net.ipv4.conf.default.accept_redirects = 0
net.ipv4.conf.all.send_redirects = 0
net.ipv4.conf.default.send_redirects = 0
net.ipv4.conf.all.accept_source_route = 0
net.ipv4.conf.default.accept_source_route = 0
EOF
    # A kernel booted with ipv6.disable=1 has no net.ipv6 tree at all:
    # writing those keys would fail at every boot and read as drift forever.
    if _sysctl_key_present net.ipv6.conf.all.forwarding; then
      cat <<EOF
net.ipv6.conf.all.forwarding = 1
net.ipv6.conf.all.accept_ra = 2
net.ipv6.conf.default.accept_ra = 2
EOF
      # Forwarding makes the kernel ignore RAs, silently killing the IPv6
      # default route on SLAAC providers after a reboot; accept_ra=2 keeps
      # them. Per-interface only where the link already uses RA: a static
      # link held at 0 by networkd would revert us forever (false drift).
      # The leading "-" lets systemd-sysctl skip it if the link is absent.
      local iface_ra
      if [[ -n $ST_F_IFACE ]]; then
        iface_ra="$(sysctl_get "net.ipv6.conf.${ST_F_IFACE}.accept_ra")"
        [[ $iface_ra =~ ^[1-9] ]] && printf -- '-net.ipv6.conf.%s.accept_ra = 2\n' "$ST_F_IFACE"
      fi
    fi
  fi

  # Value-producing helper captured via `rendered="$(_sysctl_render)"`: a
  # trailing false conditional would otherwise propagate and trip errexit.
  return 0
}

# sysctl_file_in_use — the file this host's tuning lives in (the legacy
# name until the next optimize run moves it).
sysctl_file_in_use() {
  if [[ ! -f $ST_SYSCTL_FILE && -f $ST_SYSCTL_FILE_LEGACY ]]; then
    printf '%s' "$ST_SYSCTL_FILE_LEGACY"
  else
    printf '%s' "$ST_SYSCTL_FILE"
  fi
}

# _sysctl_later_files — every sysctl file applied AFTER ours: drop-ins whose
# name sorts later (any systemd-sysctl directory), plus /etc/sysctl.conf,
# which `sysctl --system` and `sysctl -p` apply last no matter what.
# Symlinks are resolved and each target is listed once.
_sysctl_later_files() {
  local ours f base
  local -A seen=()
  ours="$(basename "$ST_SYSCTL_FILE")"
  for f in /etc/sysctl.d/*.conf /run/sysctl.d/*.conf /usr/local/lib/sysctl.d/*.conf \
    /usr/lib/sysctl.d/*.conf /lib/sysctl.d/*.conf "$ST_SYSCTL_MAIN"; do
    [[ -f $f ]] || continue
    base="$(basename "$f")"
    if [[ $f != "$ST_SYSCTL_MAIN" ]]; then
      [[ $base > $ours ]] || continue
      [[ $base == *server-tools* ]] && continue
    fi
    f="$(readlink -f "$f" 2>/dev/null)" || continue
    [[ -z ${seen[$f]:-} ]] || continue
    seen[$f]=1
    printf '%s\n' "$f"
  done
  return 0
}

# _sysctl_conflicts RENDERED FILE... — "file<TAB>key<TAB>value" for every key
# a later FILE sets to a value different from ours (it would win at boot).
_sysctl_conflicts() {
  local rendered="$1" line key value f
  shift
  local -A intent=()
  while IFS= read -r line; do
    [[ -z $line || $line == \#* || $line != *=* ]] && continue
    key="${line%%=*}"
    key="${key//[[:space:]]/}"
    key="${key#-}"
    value="${line#*=}"
    intent[$key]="$(tr -s ' \t' ' ' <<<"${value#"${value%%[![:space:]]*}"}")"
  done <<<"$rendered"
  for f in "$@"; do
    while IFS= read -r line || [[ -n $line ]]; do
      [[ $line =~ ^[[:space:]]*-?([a-z0-9_./-]+)[[:space:]]*=[[:space:]]*(.*[^[:space:]])[[:space:]]*$ ]] || continue
      key="${BASH_REMATCH[1]//\//.}"
      value="$(tr -s ' \t' ' ' <<<"${BASH_REMATCH[2]}")"
      [[ -n ${intent[$key]:-} && ${intent[$key]} != "$value" ]] || continue
      printf '%s\t%s\t%s\n' "$f" "$key" "$value"
    done <"$f"
  done
  return 0
}

# _sysctl_neutralize FILE KEY... — comment out KEY lines in FILE (tracked;
# rollback restores it). Only ever used on /etc/sysctl.conf: any other later
# file belongs to a package or another tool and is reported instead.
_sysctl_neutralize() {
  local file="$1" line key text=''
  shift
  local -A drop=()
  for key in "$@"; do drop[$key]=1; done
  while IFS= read -r line || [[ -n $line ]]; do
    if [[ $line =~ ^[[:space:]]*-?([a-z0-9_./-]+)[[:space:]]*= ]]; then
      key="${BASH_REMATCH[1]//\//.}"
      if [[ -n ${drop[$key]:-} ]]; then
        text+="# [server-tools] superseded by $(basename "$ST_SYSCTL_FILE"): ${line}"$'\n'
        continue
      fi
    fi
    text+="${line}"$'\n'
  done <"$file"
  st_track_file "$file"
  printf '%s' "$text" >"$file"
}

# _sysctl_resolve_conflicts RENDERED — make our values the ones the kernel
# gets at boot and after anyone's `sysctl --system` / `sysctl -p`.
_sysctl_resolve_conflicts() {
  local conflicts f key _value main others=''
  local -a later=() main_keys=()
  mapfile -t later < <(_sysctl_later_files)
  ((${#later[@]})) || return 0
  conflicts="$(_sysctl_conflicts "$1" "${later[@]}")"
  [[ -n $conflicts ]] || return 0
  main="$(readlink -f "$ST_SYSCTL_MAIN" 2>/dev/null)" || main="$ST_SYSCTL_MAIN"
  while IFS=$'\t' read -r f key _value; do
    if [[ $f == "$main" ]]; then
      main_keys+=("$key")
    else
      others+="${others:+, }${key} (${f})"
    fi
  done <<<"$conflicts"
  if ((${#main_keys[@]})); then
    _sysctl_neutralize "$main" "${main_keys[@]}"
    log_note "/etc/sysctl.conf overrode ${#main_keys[@]} key(s) at boot — commented out there (tracked): $(join_sp "${main_keys[@]}")."
  fi
  [[ -n $others ]] && log_warn "Applied after ours at boot and left as-is (another package/tool owns them): ${others}."
  return 0
}

# _sysctl_key_present KEY — 0 when the running kernel has KEY at all.
_sysctl_key_present() {
  [[ -e /proc/sys/${1//.//} ]]
}

# _sysctl_values_match KEY ACTUAL EXPECTED
_sysctl_values_match() {
  case "$1" in
    net.ipv4.ip_local_reserved_ports)
      # Coverage, not equality: the intent is rebuilt from the live system
      # on every render; reserving MORE than asked is harmless, a missing
      # port is the hazard (reported separately by Doctor).
      ports_covered "$3" "$2"
      ;;
    *)
      [[ "$(tr -s ' \t' ' ' <<<"$2")" == "$(tr -s ' \t' ' ' <<<"$3")" ]]
      ;;
  esac
}

# sysctl_verify [RENDERED] — compare the live kernel against the intent.
# 0 when everything matches, 3 on drift, 2 when never configured. The caller
# passes the text it wrote: re-rendering would read live inputs again.
# A key the running kernel does not have (module absent, IPv6 disabled at
# boot, a container kernel) is listed in ST_SYSCTL_UNSUPPORTED, not drift:
# nothing on this host could make it match.
ST_SYSCTL_DRIFT=()
ST_SYSCTL_UNSUPPORTED=()

sysctl_verify() {
  ST_SYSCTL_DRIFT=()
  ST_SYSCTL_UNSUPPORTED=()
  local rendered="${1:-}" line key expected actual
  if [[ -z $rendered ]]; then
    local file
    file="$(sysctl_file_in_use)"
    [[ -f $file ]] || return 2
    rendered="$(cat "$file")"
  fi

  while IFS= read -r line; do
    [[ -z $line || $line == \#* ]] && continue
    expected="${line#*=}"
    expected="${expected#"${expected%%[![:space:]]*}"}"
    key="${line%%=*}"
    key="${key//[[:space:]]/}"
    key="${key#-}"
    if ! _sysctl_key_present "$key"; then
      ST_SYSCTL_UNSUPPORTED+=("$key")
      continue
    fi
    actual="$(sysctl_get "$key")"
    _sysctl_values_match "$key" "$actual" "$expected" ||
      ST_SYSCTL_DRIFT+=("${key}|${actual}|${expected}")
  done <<<"$rendered"

  ((${#ST_SYSCTL_DRIFT[@]} == 0)) && return 0
  return 3
}

# sysctl_dry_run — the exact config this run would write, diffed against the
# live kernel. Applies NOTHING and tracks nothing.
sysctl_dry_run() {
  local rendered entry key actual expected total
  rendered="$(_sysctl_render)"
  printf '%s[Rendered %s]%s\n%s\n\n' "$C_TITLE" "$ST_SYSCTL_FILE" "$C_RESET" "$rendered"
  printf '%s[Diff vs live kernel]%s\n' "$C_TITLE" "$C_RESET"
  total="$(grep -cE '^-?[a-z]' <<<"$rendered")"
  # Drift is the expected outcome of a dry run, not an error.
  sysctl_verify "$rendered" || log_debug "dry-run: ${#ST_SYSCTL_DRIFT[@]} key(s) differ"
  if ((${#ST_SYSCTL_DRIFT[@]} == 0)); then
    printf '  (kernel already matches this plan)\n'
  else
    for entry in "${ST_SYSCTL_DRIFT[@]}"; do
      IFS='|' read -r key actual expected <<<"$entry"
      printf '  %s%-50s%s %s -> %s\n' "$C_KEY" "$key" "$C_RESET" "$actual" "$expected"
    done
  fi
  printf '\n%s%d of %d keys would change. Nothing was applied.%s\n' \
    "$C_WARN" "${#ST_SYSCTL_DRIFT[@]}" "$total" "$C_RESET"
  if ((${#ST_SYSCTL_UNSUPPORTED[@]})); then
    printf '%sNot present in this kernel (skipped at apply):%s %s\n' "$C_MUTED" "$C_RESET" \
      "$(join_sp "${ST_SYSCTL_UNSUPPORTED[@]}")"
  fi
  local -a later=()
  local conflicts
  mapfile -t later < <(_sysctl_later_files)
  if ((${#later[@]})); then
    conflicts="$(_sysctl_conflicts "$rendered" "${later[@]}")"
    if [[ -n $conflicts ]]; then
      printf '\n%s[Applied after ours at boot — would override]%s\n' "$C_TITLE" "$C_RESET"
      awk -F'\t' '{printf "  %-50s %s  (%s)\n", $2, $3, $1}' <<<"$conflicts"
      printf '  %sA real run comments these out of /etc/sysctl.conf (tracked); other files are only reported.%s\n' "$C_MUTED" "$C_RESET"
    fi
  fi
}

# _sysctl_conntrack_module — load nf_conntrack and size its hash table with
# the table itself (a module parameter, persisted via modprobe.d).
_sysctl_conntrack_module() {
  modprobe nf_conntrack 2>/dev/null ||
    log_warn "nf_conntrack module unavailable — conntrack keys may not apply."
  # Ceiling, like the table size: a larger running hash is never shrunk.
  local hashsize=$((ST_CONNTRACK / 4)) cur
  cur="$(cat /sys/module/nf_conntrack/parameters/hashsize 2>/dev/null)" || cur=''
  [[ $cur =~ ^[0-9]+$ ]] && ((cur > hashsize)) && hashsize="$cur"
  st_track_file "$ST_MODPROBE_FILE"
  mkdir -p "$(dirname "$ST_MODPROBE_FILE")"
  printf '# Generated by %s v%s\noptions nf_conntrack hashsize=%s\n' \
    "$ST_NAME" "$ST_VERSION" "$hashsize" >"$ST_MODPROBE_FILE"
  if [[ -w /sys/module/nf_conntrack/parameters/hashsize ]]; then
    st_set_runtime /sys/module/nf_conntrack/parameters/hashsize "$hashsize" ||
      log_warn "Could not resize the conntrack hash table live (persisted for next boot)."
  fi
}

sysctl_apply() {
  if ! has_cmd sysctl; then
    log_error "sysctl command not found — cannot tune the kernel."
    return 1
  fi

  local -a modules=()
  [[ $ST_CC == bbr ]] && modules+=(tcp_bbr)
  # Loaded at boot before systemd-sysctl, or the conntrack keys would be
  # missing when the file is applied (Docker/UFW load the module later).
  if ((ST_P_CONNTRACK)); then
    _sysctl_conntrack_module
    modules+=(nf_conntrack)
  fi

  # Rendered exactly once: the same text is written and later verified.
  local rendered
  rendered="$(_sysctl_render)"
  st_track_file "$ST_SYSCTL_FILE"
  mkdir -p "$(dirname "$ST_SYSCTL_FILE")"
  printf '%s\n' "$rendered" >"$ST_SYSCTL_FILE"
  if [[ -f $ST_SYSCTL_FILE_LEGACY ]]; then
    # Moved to the later-sorting name (tracked: rollback brings it back).
    st_track_file "$ST_SYSCTL_FILE_LEGACY"
    rm -f "$ST_SYSCTL_FILE_LEGACY"
  fi
  _sysctl_resolve_conflicts "$rendered"

  if ((${#modules[@]} > 0)); then
    st_track_file "$ST_MODULES_FILE"
    mkdir -p "$(dirname "$ST_MODULES_FILE")"
    {
      printf '# Generated by %s v%s\n' "$ST_NAME" "$ST_VERSION"
      printf '%s\n' "${modules[@]}"
    } >"$ST_MODULES_FILE"
  fi

  # Per-key errors land in the log instead of vanishing — the verification
  # below is what decides the outcome, not sysctl's own exit status.
  sysctl --system >/dev/null 2>>"$ST_LOG_FILE" ||
    log_debug "sysctl --system reported errors (verified below)."

  local rc=0
  if ! sysctl_verify "$rendered"; then
    local entry key actual expected names=''
    for entry in "${ST_SYSCTL_DRIFT[@]}"; do
      IFS='|' read -r key actual expected <<<"$entry"
      names+="${key} "
      log_info "drift: ${key} is '${actual}', expected '${expected}'"
    done
    log_warn "${#ST_SYSCTL_DRIFT[@]} key(s) did not take the expected value: ${names% }"
    virt_is_container &&
      log_note "In a ${ST_F_VIRT} container many kernel keys belong to the host and cannot be changed from inside."
    rc=3
  fi
  if ((${#ST_SYSCTL_UNSUPPORTED[@]})); then
    log_note "Not present in this kernel (skipped): $(join_sp "${ST_SYSCTL_UNSUPPORTED[@]}")."
  fi
  log_info "sysctl applied: cc=$(sysctl_get net.ipv4.tcp_congestion_control), qdisc=${ST_QDISC}, tier=${ST_TIER}, roles=${ST_ROLES}"
  return "$rc"
}
