# shellcheck shell=bash
# ============================================================================
# tuners/mss.sh — TCP MSS clamping for forwarded traffic.
#
# The classic "VPN/tunnel connects but sites do not load" fix, and a CPU fix
# too: without it, full-size segments forwarded into a smaller-MTU tunnel
# (GRE 1476/1430, WireGuard 1420) are fragmented or bounced with ICMP on
# every packet. 2.4.5 makes it a Quick Optimize step for vpn/tunnel/relay roles.
#
# Backends: iptables (legacy or iptables-nft) when present, else native nft.
# Persistence is a oneshot unit whose ExecStart is idempotent (check before
# add) and whose ExecStop removes the rule — so rollback clears it live (pre-2.4.5
# unit had no ExecStop and re-appended a duplicate on every restart).
# ============================================================================

readonly ST_MSS_UNIT='/etc/systemd/system/server-tools-mss.service'
readonly ST_MSS_NFT='/etc/server-tools/mss.nft'
readonly ST_MSS_NFT_TABLE='server_tools_mss'
# The comma in SYN,RST is iptables syntax, not an array-separator mistake.
# shellcheck disable=SC2054
readonly -a ST_MSS_RULE=(-p tcp --tcp-flags SYN,RST SYN -j TCPMSS --clamp-mss-to-pmtu)

# _mss_ufw_persist — UFW rebuilds its ruleset on `ufw reload`; when UFW owns
# the firewall the clamp also lives in before.rules. Tracked, and reverted if
# UFW refuses the edit.
_mss_ufw_persist() {
  local rules='/etc/ufw/before.rules'
  has_cmd ufw || return 2
  [[ -f $rules ]] || return 2
  grep -q 'server-tools MSS' "$rules" 2>/dev/null && return 0

  st_track_file "$rules"
  cat >>"$rules" <<'EOF'

# --- server-tools MSS clamping (managed block, safe to remove as a whole)
*mangle
:FORWARD - [0:0]
-A FORWARD -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --clamp-mss-to-pmtu
COMMIT
EOF
  if ufw status 2>/dev/null | grep -q '^Status: active'; then
    if ! ufw reload >/dev/null 2>>"$ST_LOG_FILE"; then
      cp -a "${ST_RUN_BACKUP_DIR}${rules}" "$rules"
      log_warn "UFW rejected the before.rules change — reverted; the oneshot unit still persists the clamp."
      return 3
    fi
  fi
  return 0
}

_mss_write_nft() {
  st_track_file "$ST_MSS_NFT"
  mkdir -p "$(dirname "$ST_MSS_NFT")"
  cat >"$ST_MSS_NFT" <<EOF
# Generated by ${ST_NAME} v${ST_VERSION} — MSS clamping (native nftables).
table inet ${ST_MSS_NFT_TABLE} {
  chain forward {
    type filter hook forward priority mangle; policy accept;
    tcp flags syn / syn,rst tcp option maxseg size set rt mtu
  }
}
EOF
}

# _mss_unit_iptables — ExecStart lines check before adding, ExecStop removes.
_mss_unit_iptables() {
  local ipt ip6t rule bin
  ipt="$(command -v iptables)"
  ip6t="$(command -v ip6tables)" || ip6t=''
  # join_sp, not "${arr[*]}": the global IFS would join with newlines and
  # split ExecStart= across several broken lines (a shipped pre-2.4.5 bug).
  rule="$(join_sp "${ST_MSS_RULE[@]}")"
  printf '# Generated by %s v%s\n' "$ST_NAME" "$ST_VERSION"
  printf '[Unit]\nDescription=ServerTools MSS clamping (oneshot, exits after boot)\n'
  printf 'After=network-pre.target %s\nWants=network-pre.target\n\n' "$ST_FW_AFTER"
  printf '[Service]\nType=oneshot\nRemainAfterExit=yes\n'
  for bin in "$ipt" "$ip6t"; do
    [[ -n $bin ]] || continue
    # "-" prefix on IPv6: a host without IPv6 netfilter must not fail the unit.
    printf "ExecStart=%s/bin/sh -c '%s -w -t mangle -C FORWARD %s 2>/dev/null || %s -w -t mangle -A FORWARD %s'\n" \
      "$([[ $bin == "$ip6t" ]] && printf -- '-')" "$bin" "$rule" "$bin" "$rule"
    printf 'ExecStop=-%s -w -t mangle -D FORWARD %s\n' "$bin" "$rule"
  done
  printf '\n[Install]\nWantedBy=multi-user.target\n'
}

_mss_unit_nft() {
  local nft
  nft="$(command -v nft)"
  printf '# Generated by %s v%s\n' "$ST_NAME" "$ST_VERSION"
  printf '[Unit]\nDescription=ServerTools MSS clamping, nftables (oneshot, exits after boot)\n'
  printf 'After=network-pre.target %s\nWants=network-pre.target\n\n' "$ST_FW_AFTER"
  printf '[Service]\nType=oneshot\nRemainAfterExit=yes\n'
  printf 'ExecStartPre=-%s delete table inet %s\n' "$nft" "$ST_MSS_NFT_TABLE"
  printf 'ExecStart=%s -f %s\n' "$nft" "$ST_MSS_NFT"
  printf 'ExecStop=-%s delete table inet %s\n' "$nft" "$ST_MSS_NFT_TABLE"
  printf '\n[Install]\nWantedBy=multi-user.target\n'
}

# mss_apply — runner step and menu action. 0 ok, 1 failed, 2 skipped, 3 warn.
mss_apply() {
  local backend='' rc=0
  if fw_has_iptables; then
    backend=iptables
  elif fw_has_nft; then
    backend=nft
  else
    log_warn "Neither iptables nor nft is available — MSS clamping skipped."
    return 2
  fi

  if [[ $backend == iptables ]]; then
    if ! fw_rule_ensure iptables mangle FORWARD "${ST_MSS_RULE[@]}"; then
      log_error "Could not add the IPv4 MSS rule — see the log."
      return 1
    fi
    if has_cmd ip6tables; then
      fw_rule_ensure ip6tables mangle FORWARD "${ST_MSS_RULE[@]}" ||
        log_note "IPv6 MSS rule not added (no IPv6 netfilter here)."
    fi
    local rc_ufw=0
    _mss_ufw_persist || rc_ufw=$?
    ((rc_ufw == 3)) && rc=3
  else
    _mss_write_nft
    nft delete table inet "$ST_MSS_NFT_TABLE" 2>/dev/null || log_debug "no previous MSS table"
    if ! nft -f "$ST_MSS_NFT" 2>>"$ST_LOG_FILE"; then
      log_error "nft rejected the MSS table — see the log."
      return 1
    fi
  fi

  if systemd_usable; then
    st_track_file "$ST_MSS_UNIT"
    if [[ $backend == iptables ]]; then
      _mss_unit_iptables >"$ST_MSS_UNIT"
    else
      _mss_unit_nft >"$ST_MSS_UNIT"
    fi
    systemd_enable_oneshot server-tools-mss.service || rc=3
  else
    log_warn "No systemd — the MSS clamp is active now but will not survive a reboot."
    rc=3
  fi
  log_note "MSS clamped to the path MTU on forwarded TCP (${backend})."
  log_info "MSS clamping applied (backend=${backend}, rc=${rc})."
  return "$rc"
}

# mss_menu — interactive wrapper (Network tools).
mss_menu() {
  ui_section "MSS clamping (TCP over tunnels/NAT)"
  printf 'Clamps TCP MSS to the path MTU on forwarded traffic. Fixes "VPN connects\n'
  printf 'but sites do not load" and avoids per-packet fragmentation into tunnels.\n'
  ui_confirm "Apply MSS clamping now?" || return 0
  local rc=0
  mss_apply || rc=$?
  case "$rc" in
    0) printf '%sMSS clamping active%s and persisted (oneshot unit — nothing stays running).\n' "$C_OK" "$C_RESET" ;;
    3) printf '%sMSS clamping active with warnings%s — see the log.\n' "$C_WARN" "$C_RESET" ;;
    *) printf '%sMSS clamping was not applied%s — see the log.\n' "$C_ERR" "$C_RESET" ;;
  esac
  return 0
}

# mss_verify — 0 rule live, 2 never configured, 3 configured but missing.
mss_verify() {
  if fw_rule_present iptables mangle FORWARD "${ST_MSS_RULE[@]}"; then
    return 0
  fi
  fw_nft_table_present inet "$ST_MSS_NFT_TABLE" && return 0
  [[ -f $ST_MSS_UNIT ]] && return 3
  return 2
}
