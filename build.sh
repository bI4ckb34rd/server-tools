#!/usr/bin/env bash
# ============================================================================
# build.sh — compiles the modular src/ tree into dist/server-tools.sh.
# See docs/ARCHITECTURE.md. Never edit dist/ by hand.
# ============================================================================
set -Eeuo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC_DIR="${ROOT_DIR}/src"
OUT_FILE="${ROOT_DIR}/dist/server-tools.sh"
VERSION="$(tr -d '[:space:]' <"${ROOT_DIR}/VERSION")"

# Concatenation order: header first (strict mode, constants), then lib →
# state → engine → tuners → features → ui, and the entrypoint last. Bash
# resolves functions at call time, so only top-level statements (readonly
# constants, the final main call) depend on this order.
SOURCES=(
  00-header.sh
  lib/term.sh
  lib/log.sh
  lib/ui.sh
  lib/sys.sh
  lib/net.sh
  lib/fw.sh
  lib/deps.sh
  state/config.sh
  state/manifest.sh
  state/backup.sh
  engine/facts.sh
  engine/roles.sh
  engine/capacity.sh
  engine/policy.sh
  engine/runner.sh
  tuners/sysctl.sh
  tuners/qdisc.sh
  tuners/nic.sh
  tuners/mss.sh
  tuners/tunnel.sh
  tuners/swap.sh
  tuners/limits.sh
  tuners/extras.sh
  tuners/dns.sh
  features/notrack.sh
  features/flowtable.sh
  features/security.sh
  features/ipv6.sh
  features/kernel.sh
  features/mirror.sh
  features/docker.sh
  features/installer.sh
  features/tools.sh
  features/selfupdate.sh
  features/diagnose.sh
  features/sysinfo.sh
  features/doctor.sh
  state/migrate.sh
  ui/flows.sh
  ui/menu.sh
  99-main.sh
)

# Every src file must be listed exactly once — a forgotten file would build
# "successfully" into a program with missing functions.
mapfile -t _on_disk < <(cd "$SRC_DIR" && find . -name '*.sh' | sed 's#^\./##' | sort)
mapfile -t _listed < <(printf '%s\n' "${SOURCES[@]}" | sort)
if [[ "${_on_disk[*]}" != "${_listed[*]}" ]]; then
  printf 'build.sh: SOURCES does not match src/ — add/remove entries:\n' >&2
  # diff exits 1 when the lists differ — that output IS the report.
  diff <(printf '%s\n' "${_listed[@]}") <(printf '%s\n' "${_on_disk[@]}") >&2 || :
  exit 1
fi

mkdir -p "${ROOT_DIR}/dist"

{
  printf '#!/usr/bin/env bash\n'
  printf '# =========================================================================\n'
  printf '# ServerTools v%s — single-file build\n' "$VERSION"
  printf '# Generated from src/ by build.sh — DO NOT EDIT THIS FILE DIRECTLY.\n'
  printf '# https://github.com/Sir-Adnan/server-tools\n'
  printf '# =========================================================================\n'
  for src in "${SOURCES[@]}"; do
    printf '\n# ------------------------- src/%s -------------------------\n' "$src"
    # Strip per-file shebang/shellcheck directives; inject the version string.
    sed -e '\|^#!/usr/bin/env bash$|d' \
      -e '/^# shellcheck shell=bash$/d' \
      -e "s/@VERSION@/${VERSION}/g" \
      "${SRC_DIR}/${src}"
  done
} >"$OUT_FILE"

chmod +x "$OUT_FILE"
bash -n "$OUT_FILE"
printf 'Built %s (v%s, %s lines)\n' "$OUT_FILE" "$VERSION" "$(wc -l <"$OUT_FILE" | tr -d '[:space:]')"
